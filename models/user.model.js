import mongoose from "mongoose";

const userSchema = new mongoose.Schema(
  {
    sessionId: {
      type: Number,
      required: true,
      default: 0,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
    },
    password: {
      type: String,
      required: true,
    },
  },
  { timestamps: true }
);

const User = mongoose.model("User", userSchema);

export default User;
